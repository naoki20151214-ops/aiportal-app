#!/usr/bin/env node
/**
 * Build-time allowlist for Cloudflare Pages Functions. Never trust a client-
 * supplied article ID + slug pair as proof that an article is published.
 */
import fs from "node:fs";
import path from "node:path";
import { parse } from "yaml";

const root = process.cwd();
const registry = parse(fs.readFileSync(path.join(root, "content/registry/knowledge-nodes.yml"), "utf8"));
if (!Array.isArray(registry.nodes) || registry.nodes.length !== registry.nodeCount)
  throw new Error("Invalid main Registry; cannot generate feedback allowlist");

const map = {};
for (const node of registry.nodes) {
  if (node.status !== "published") continue;
  if (!/^(BAS|GEN|AGT|PHY|INF|SOC|NEWS)-\d{4}$/.test(node.id) ||
      !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(node.slug) || map[node.id])
    throw new Error("Invalid or duplicate published Registry node: " + node.id);
  map[node.id] = node.slug;
}
const outputPath = path.join(root, "src/generated/published-article-slugs.ts");
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath,
  "// GENERATED by scripts/generate-feedback-article-map.mjs. Do not edit manually.\n" +
  "export const publishedArticleSlugById = " + JSON.stringify(map, null, 2) + " as const;\n");
console.log("Feedback allowlist updated for " + Object.keys(map).length + " published articles.");
